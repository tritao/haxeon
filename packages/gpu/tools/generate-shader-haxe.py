#!/usr/bin/env python3
"""Generate Haxe shader programs from NativeKit shader reflection."""

import argparse
import json
import re
from pathlib import Path

TARGETS = {
    "glsl410": "Glsl410", "glsl300es": "Glsl300Es", "hlsl5": "Hlsl5",
    "metal_macos": "MetalMacos", "metal_ios": "MetalIos",
}
TYPES = {
    "float": "Float", "vec2": "Float2", "vec3": "Float3", "vec4": "Float4",
    "int": "Int", "ivec2": "Int2", "ivec3": "Int3", "ivec4": "Int4", "mat4": "Mat4",
}
IMAGE_TYPES = {"2d": "TwoD", "array": "Array", "cube": "Cube", "cube_array": "CubeArray"}


def uniform_blocks(blocks, name):
    records, methods = [], []
    for block in blocks:
        label = f"{block['stage'].capitalize()}{block['slot']}"
        record = f"{name}{label}Uniforms"
        records.append(f"typedef {record} = {{")
        methods.extend(("", f"\tpublic static inline var {label[0].lower() + label[1:]}Block = {block['slot']};",
                        f"\tpublic static function pack{label}(values:{record}):Bytes {{",
                        f"\t\tvar bytes = Bytes.alloc({block['size']});"))
        for member in block["members"]:
            field = member["name"]
            kind = member["type"]
            integer = kind == "int" or kind.startswith("ivec")
            scalar = "Int" if integer else "Float"
            setter = "setInt32" if integer else "setFloat"
            components = 16 if kind == "mat4" else (int(kind[-1]) if kind.endswith(("2", "3", "4")) else 1)
            if kind not in TYPES:
                raise ValueError(f"unsupported uniform field type {kind}")
            count = member["array_count"]
            length = count * components
            field_type = scalar if length == 1 else f"Array<{scalar}>"
            records.append(f"\tfinal {field}:{field_type};")
            if length > 1:
                methods.extend((f"\t\tif (values.{field}.length != {length})",
                                f'\t\t\tthrow BindingError.invalidArgument("{name}.pack{label}", "{field} requires {length} values");'))
            stride = member.get("array_stride", components * 4)
            for index in range(length):
                offset = member["offset"] + index // components * stride + index % components * 4
                value = f"values.{field}" if length == 1 else f"values.{field}[{index}]"
                methods.append(f"\t\tbytes.{setter}({offset}, {value});")
        records.extend(("}", ""))
        methods.extend(("\t\treturn bytes;", "\t}"))
    return records, methods


def generate(data, program, variant, name):
    if data.get("schema") != "nkgpu-shader-reflection/1":
        raise ValueError("unsupported shader reflection schema")
    backends = data["programs"][program][variant]["targets"]
    canonical = next(iter(backends.values()))
    records, packers = uniform_blocks(canonical["uniform_blocks"], name)
    lines = [
        "// Generated by packages/gpu/tools/generate-shader-haxe.py. Do not edit.",
        "import haxeon.gpu.Enums;",
        "import haxeon.gpu.Renderer;",
        "import haxeon.gpu.Shader;",
        "import haxeon.gpu.ShaderProgram;",
        "import haxeon.platform.BindingError;",
    ]
    if records:
        lines.append("import haxe.io.Bytes;")
    lines.extend(("", *records, f"class {name} {{"))
    for attr in canonical["attributes"]:
        lines.append(f"\tpublic static inline var {attr['name']} = {attr['slot']};")
    lines.extend(packers)
    lines.extend(("", "\tpublic static final program = new ShaderProgram(["))
    for attr in canonical["attributes"]:
        semantic = attr["semantic"]
        lines.append(f"\t\t{{slot: {attr['slot']}, name: {json.dumps(attr['name'])}, "
                     f"semantic: {json.dumps(semantic['name'])}, semanticIndex: {semantic['index']}}},")
    lines.append("\t], [")
    for slang, description in backends.items():
        if description["storage_buffers"]:
            raise ValueError(f"{program}: storage buffers are unsupported in shader tables")
        lines.extend(("\t\t{", f"\t\t\ttarget: ShaderTarget.{TARGETS[slang]},"))
        for stage in ("vertex", "fragment"):
            entry = description["stages"][stage]
            expected = "main0" if slang.startswith("metal_") else "main"
            if entry["entry_point"] != expected:
                raise ValueError(f"{program}: unsupported {stage} entry for {slang}")
            lines.append(f"\t\t\t{stage}: {json.dumps(data['sources'][entry['source']])},")
        lines.append("\t\t\tblocks: [")
        for block in description["uniform_blocks"]:
            lines.append(f"\t\t\t\t{{slot: {block['slot']}, stage: ShaderStage.{block['stage'].capitalize()}, size: {block['size']}}},")
        lines.extend(("\t\t\t],", "\t\t\tuniforms: ["))
        for block in description["uniform_blocks"]:
            for index, member in enumerate(block["gl_uniforms"]):
                lines.append(f"\t\t\t\t{{block: {block['slot']}, member: {index}, name: {json.dumps(member['name'])}, "
                             f"type: UniformType.{TYPES[member['type']]}, count: {member['array_count']}}},")
        lines.extend(("\t\t\t],", "\t\t\ttextures: ["))
        images = {image["slot"]: image for image in description["images"]}
        for pair in description["image_sampler_pairs"]:
            image = images[pair["image_slot"]]
            if image["sample_type"] != "float" or image["multisampled"]:
                raise ValueError(f"{program}: unsupported texture sample type")
            lines.append(f"\t\t\t\t{{view: {image['slot']}, sampler: {pair['sampler_slot']}, "
                         f"stage: ShaderStage.{image['stage'].capitalize()}, type: ImageType.{IMAGE_TYPES[image['type']]}, "
                         f"name: {json.dumps(pair['name'])}}},")
        lines.extend(("\t\t\t]", "\t\t},"))
    lines.extend(("\t]);", "", "\tpublic static function create(renderer:Renderer):Shader",
                  "\t\treturn Shader.create(renderer, program);", "}", ""))
    return "\n".join(lines).encode()


def generate_program(data, program, name):
    variants = sorted(data["programs"][program])
    if len(variants) == 1:
        return generate(data, program, variants[0], name)

    choices = {}
    for variant in variants:
        if not re.fullmatch(r"[a-zA-Z_][a-zA-Z_0-9]*", variant):
            raise ValueError(f"{program}: invalid variant identifier {variant}")
        label = variant[0].upper() + variant[1:]
        if label in choices:
            raise ValueError(f"{program}: duplicate variant identifier {label}")
        choices[label] = variant

    enum_type = name + "Variant"
    lines = [
        "// Generated by packages/gpu/tools/generate-shader-haxe.py. Do not edit.",
        "import haxe.io.Bytes;",
        "import haxeon.gpu.Enums;",
        "import haxeon.gpu.Renderer;",
        "import haxeon.gpu.Shader;",
        "import haxeon.gpu.ShaderProgram;",
        "import haxeon.platform.BindingError;",
        "",
        f"enum {enum_type} {{",
        *(f"\t{label};" for label in choices),
        "}",
        "",
        f"class {name} {{",
        f"\tpublic static function create(renderer:Renderer, variant:{enum_type}):Shader {{",
        "\t\treturn switch variant {",
        *(f"\t\t\tcase {label}: {name}{label}.create(renderer);" for label in choices),
        "\t\t}",
        "\t}",
        "}",
        "",
    ]
    for label, variant in choices.items():
        generated = generate(data, program, variant, name + label).decode()
        lines.extend(line for line in generated.splitlines()
                     if not line.startswith(("// Generated", "import ")))
    return ("\n".join(lines) + "\n").encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reflection", type=Path)
    parser.add_argument("program")
    parser.add_argument("output", type=Path)
    parser.add_argument("--variant")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        data = json.loads(args.reflection.read_text(encoding="utf-8"))
        output = (generate_program(data, args.program, args.output.stem) if args.variant is None
                  else generate(data, args.program, args.variant, args.output.stem))
        if args.check:
            if args.output.read_bytes() != output:
                raise ValueError(f"{args.output} is stale")
        else:
            args.output.write_bytes(output)
    except (KeyError, OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
