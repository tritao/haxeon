#!/usr/bin/env python3
"""Generates the interface-dispatch benchmark for N implementors (docs/INTERFACE_VALUES.md): the ways a call through an interface value could be
dispatched when the value is the object, measured on HashLink.

  python3 generate.py N OUT.hx

  linear    a chain of class-id comparisons (the closed-world switch the Wasm backends emit)
  jump      `switch` on the class id
  binary    a binary search on the class id
  selector  one global function table indexed by classId + selectorOffset (Dart-style): an array get and a closure call; the id is a field
  selector-m  the same, with the class id read through a class method (no per-object storage): one more method-table call
  today     the call through an interface value (an allocating virtual adapter)
"""
import sys

n = int(sys.argv[1])
out = sys.argv[2]
lines = []
w = lines.append
w("// Generated by generate.py: %d implementors." % n)
w("interface Reader { function read():Int; }")
w("class Base implements Reader { public final id:Int; public var v:Int; public function new(id:Int, v:Int) { this.id = id; this.v = v; } public function read():Int return v; public function cid():Int return id; }")
for k in range(n):
    w("class C%d extends Base { public function new(v:Int) super(%d, v); override public function read():Int return v + %d; override public function cid():Int return %d; }" % (k, k, k + 1, k))
w("class Main {")
w("\tstatic inline final COUNT = 1024;")
w("\tstatic inline final CALLS = 10000000;")
w("\tstatic inline final RUNS = 3;")
w("\tstatic inline final SELECTOR_OFFSET = 0;")
w("\tstatic var table:Array<Base->Int> = [")
w(",\n".join("\t\to -> (cast o : C%d).read()" % k for k in range(n)))
w("\t];")

def call(k):
    return "(cast o : C%d).read()" % k

def binary(lo, hi, indent):
    pad = "\t" * indent
    if lo == hi:
        return "%sreturn %s;" % (pad, call(lo))
    mid = (lo + hi) // 2
    return "%sif (id <= %d) {\n%s\n%s} else {\n%s\n%s}" % (pad, mid, binary(lo, mid, indent + 1), pad, binary(mid + 1, hi, indent + 1), pad)

w("\t@:noinline static function viaLinear(o:Base, id:Int):Int {")
for k in range(n - 1):
    w("\t\tif (id == %d) return %s;" % (k, call(k)))
w("\t\treturn %s;" % call(n - 1))
w("\t}")
w("\t@:noinline static function viaJump(o:Base, id:Int):Int {")
w("\t\tswitch id {")
for k in range(n - 1):
    w("\t\t\tcase %d: return %s;" % (k, call(k)))
w("\t\t\tdefault: return %s;" % call(n - 1))
w("\t\t}")
w("\t}")
w("\t@:noinline static function viaBinary(o:Base, id:Int):Int {")
w(binary(0, n - 1, 2))
w("\t}")
w("\t@:noinline static function viaSelector(o:Base, id:Int):Int return table[id + SELECTOR_OFFSET](o);")
w("\t@:noinline static function viaSelectorMethod(o:Base):Int return table[o.cid() + SELECTOR_OFFSET](o);")
w("""
	static function best(run:Void->Int):Float {
		var bestTime = 1e30, sink = 0;
		for (_ in 0...RUNS) {
			var start = Sys.time();
			sink += run();
			var elapsed = Sys.time() - start;
			if (elapsed < bestTime) bestTime = elapsed;
		}
		if (sink == 42) Sys.println("");
		return bestTime * 1e9 / CALLS;
	}

	static function show(name:String, value:Float):Void
		Sys.println(StringTools.rpad(name, " ", 11) + Math.round(value * 100) / 100);

	static function main():Int {
		var objects:Array<Base> = [], views:Array<Reader> = [];
		for (i in 0...COUNT) {
			var o:Base = make(i % %(n)d, i);
			objects.push(o);
			views.push(o);
		}
		Sys.println("implementors %(n)d (ns per call)");
		show("today", best(() -> { var s = 0; for (i in 0...CALLS) s += views[i & (COUNT - 1)].read(); return s; }));
		show("linear", best(() -> { var s = 0; for (i in 0...CALLS) { var o = objects[i & (COUNT - 1)]; s += viaLinear(o, o.id); } return s; }));
		show("jump", best(() -> { var s = 0; for (i in 0...CALLS) { var o = objects[i & (COUNT - 1)]; s += viaJump(o, o.id); } return s; }));
		show("binary", best(() -> { var s = 0; for (i in 0...CALLS) { var o = objects[i & (COUNT - 1)]; s += viaBinary(o, o.id); } return s; }));
		show("selector-m", best(() -> { var s = 0; for (i in 0...CALLS) s += viaSelectorMethod(objects[i & (COUNT - 1)]); return s; }));
		show("selector", best(() -> { var s = 0; for (i in 0...CALLS) { var o = objects[i & (COUNT - 1)]; s += viaSelector(o, o.id); } return s; }));
		return 42;
	}
""".replace("%(n)d", str(n)))
w("\tstatic function make(k:Int, v:Int):Base {")
w("\t\tswitch k {")
for k in range(n - 1):
    w("\t\t\tcase %d: return new C%d(v);" % (k, k))
w("\t\t\tdefault: return new C%d(v);" % (n - 1))
w("\t\t}")
w("\t}")
w("}")
open(out, "w").write("\n".join(lines) + "\n")
